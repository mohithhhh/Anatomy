#!/usr/bin/env node
/**
 * Build data/content/definitions.json from the Uberon anatomy ontology (CC BY 3.0).
 * Uberon terms carry FMA cross-references, so each atlas concept with a matching FMA ID gets a
 * sourced definition, synonyms and, where Uberon has one, a Latin name.
 *
 * Usage: node scripts/build-definitions.mjs [path/to/uberon-basic.obo]
 * Without a path it downloads the pinned release below.
 */
import { readFile, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const RELEASE = "v2026-10-01";
const URL_OBO = `https://github.com/obophenotype/uberon/releases/download/${RELEASE}/uberon-basic.obo`;

if ((process.env.HTTPS_PROXY || process.env.https_proxy) && !process.env.NODE_USE_ENV_PROXY) {
  const child = spawnSync(process.execPath, ["--no-warnings", ...process.argv.slice(1)], {
    stdio: "inherit",
    env: { ...process.env, NODE_USE_ENV_PROXY: "1" },
  });
  process.exit(child.status ?? 1);
}

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const lock = JSON.parse(await readFile(join(root, "data/models.lock.json"), "utf8"));
const atlas = JSON.parse(
  await readFile(join(root, "public/models", lock.version, "atlas.json"), "utf8"),
);
const wanted = new Set(atlas.concepts.map((c) => c.id));

const text = process.argv[2]
  ? await readFile(process.argv[2], "utf8")
  : await (await fetch(URL_OBO)).text();

const unquote = (s) => s.replace(/\\"/g, '"');
/** Drop citation markers like "[1]" and keep at most ~420 characters of whole sentences. */
const tidy = (text) => {
  const clean = text
    .replace(/\s*\[\d+\]/g, "")
    .replace(/\s+/g, " ")
    .trim();
  if (clean.length <= 420) return clean;
  const sentences = clean.match(/[^.!?]+[.!?]+(\s|$)/g) ?? [clean];
  let out = "";
  for (const sentence of sentences) {
    if ((out + sentence).length > 420 && out) break;
    out += sentence;
  }
  return out.trim();
};
const out = {};
for (const block of text.split("\n[Term]\n").slice(1)) {
  const lines = block.split("\n");
  const get = (key) =>
    lines.filter((l) => l.startsWith(`${key}: `)).map((l) => l.slice(key.length + 2));
  if (get("is_obsolete").includes("true")) continue;
  const fma = get("xref")
    .map((x) => /^FMA:(\d+)\b/.exec(x)?.[1])
    .filter(Boolean)
    .map((n) => `FMA${n}`)
    .filter((id) => wanted.has(id));
  if (!fma.length) continue;
  const id = get("id")[0];
  const defLine = get("def")[0];
  const def = defLine ? /^"((?:[^"\\]|\\.)*)"/.exec(defLine)?.[1] : undefined;
  // Auto-generated stubs ("A kidney that is part of a left side of organism") add nothing.
  const useful = def && !def.includes("[Automatically generated definition]") ? def : undefined;
  const synonyms = [];
  let latin;
  for (const s of get("synonym")) {
    const m = /^"((?:[^"\\]|\\.)*)" (EXACT|RELATED|NARROW|BROAD)\s*([A-Z_]+)?/.exec(s);
    if (!m) continue;
    const value = unquote(m[1]);
    if (m[3] === "LATIN" || / LATIN /.test(s)) latin ??= value;
    else if (m[2] === "EXACT") synonyms.push(value);
  }
  for (const conceptId of fma) {
    if (out[conceptId]) continue;
    out[conceptId] = {
      uberon: id,
      name: get("name")[0],
      ...(useful ? { definition: tidy(unquote(useful)) } : {}),
      ...(synonyms.length ? { synonyms: [...new Set(synonyms)].slice(0, 6) } : {}),
      ...(latin ? { latin } : {}),
    };
  }
}

const result = {
  $comment:
    "Generated by scripts/build-definitions.mjs from Uberon (CC BY 3.0, https://obophenotype.github.io/uberon/). Do not edit by hand.",
  source: { name: "Uberon", release: RELEASE, license: "CC BY 3.0", url: URL_OBO },
  concepts: Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b))),
};
await writeFile(
  join(root, "data/content/definitions.json"),
  `${JSON.stringify(result, null, 1)}\n`,
);
const withDef = Object.values(out).filter((c) => c.definition).length;
console.log(
  `Uberon ${RELEASE}: ${Object.keys(out).length} atlas concepts matched, ${withDef} with definitions, ${Object.values(out).filter((c) => c.latin).length} with Latin names.`,
);
