/**
 * Writes docs/content/regions-report.md so a person can spot-check region tags.
 * Usage: node scripts/content-report.ts
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { indexAtlas } from "../src/atlas/atlas-index.ts";
import type { Atlas } from "../src/atlas/types.ts";
import { buildContent } from "../src/content/content.ts";
import { REGIONS } from "../src/content/regions.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const lock = JSON.parse(readFileSync(join(root, "data/models.lock.json"), "utf8"));
const atlas = JSON.parse(
  readFileSync(join(root, "public/models", lock.version, "atlas.json"), "utf8"),
) as Atlas;
const content = buildContent(indexAtlas(atlas));

const lines: string[] = [
  "# Region tags: review report",
  "",
  "Generated by `node scripts/content-report.ts`. Each structure gets one primary region, from its",
  "own name, then the names of the small groups it belongs to, then its position in the model.",
  "Rules live in `src/content/regions.ts`. Read the samples and the position-based list, and fix",
  "any mistake with a rule or an override.",
  "",
  `Structures: ${content.items.length}.`,
  "",
  "| Region | Structures | By name | By group | By position |",
  "| --- | ---: | ---: | ---: | ---: |",
];
for (const region of REGIONS) {
  const items = content.items.filter((i) => i.region === region.id);
  const count = (source: string) => items.filter((i) => i.regionSource === source).length;
  lines.push(
    `| ${region.name} | ${items.length} | ${count("name")} | ${count("group")} | ${count("position")} |`,
  );
}
for (const region of REGIONS) {
  const items = content.items.filter((i) => i.region === region.id);
  const step = Math.max(1, Math.floor(items.length / 30));
  const sample = items.filter((_, i) => i % step === 0).slice(0, 30);
  const byPosition = items.filter((i) => i.regionSource === "position");
  lines.push("", `## ${region.name}`, "", `Sample: ${sample.map((i) => i.name).join("; ")}.`);
  lines.push(
    "",
    `Placed by position (${byPosition.length}): ${byPosition.map((i) => i.name).join("; ") || "none"}.`,
  );
}
const out = join(root, "docs/content/regions-report.md");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `${lines.join("\n")}\n`);
console.log(`Wrote ${out}`);
